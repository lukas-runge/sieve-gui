//! The root script (concept §3, decision D12).
//!
//! ManageSieve runs only one active script. sieve-gui can instead activate a
//! generated root script, named [`ROOT_SCRIPT_NAME`], that includes the
//! active scripts in order (RFC 6609). With "last move wins", it also files
//! each message into at most one folder: included scripts in single-folder
//! mode only record the folder in a global variable (RFC 5229), and the root
//! files the message into the folder recorded last.
//!
//! ```sieve
//! require ["fileinto","include","variables"];
//! global "move_to_folder";
//! include :personal :optional "Work";
//! include :personal :optional "Newsletters";
//! if not string :is "${move_to_folder}" ""
//! {
//!     fileinto "${move_to_folder}";
//! }
//! ```
//!
//! Without "last move wins", only the `require` and `include` commands remain.
//!
//! Scripts that were on the server before sieve-gui (e.g. a webmail's own
//! root script, such as Synology MailPlus' `synomc`) can be included
//! *unchanged*: sieve-gui runs them but never rewrites them, not even into
//! single-folder mode. Such includes carry a `# unchanged` comment:
//!
//! ```sieve
//! include :personal :optional "synomc"; # unchanged
//! ```

use serde::Serialize;

use crate::ast::{Argument, ClearSpans, Command, Tests};
use crate::export::{command, hash_comment, list, string, tag, test};
use crate::printer::{print_command, PrintOptions};
use crate::span::Span;

/// The name sieve-gui gives the root script on the server.
pub const ROOT_SCRIPT_NAME: &str = "sieve-gui";

/// The global variable holding the folder a message goes to.
pub const FOLDER_VARIABLE: &str = "move_to_folder";

/// The comment that marks an include as unchanged.
const UNCHANGED: &str = "unchanged";

/// What a root script does.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Root {
    /// The included scripts, in the order they run.
    pub scripts: Vec<String>,
    /// The included scripts sieve-gui must not rewrite (a subset of
    /// `scripts`).
    pub unchanged: Vec<String>,
    /// Whether it files the message into the folder recorded last.
    pub last_move_wins: bool,
    /// Whether it lost its `global` command, so the folder the included
    /// scripts record never reaches it and no message is moved. Roundcube
    /// drops `global` whenever it saves the script (fixture
    /// `roundcube/24b`). Only set with `last_move_wins`.
    pub damaged: bool,
}

/// The root script including `scripts` in this order; those also in
/// `unchanged` are marked as such.
pub fn root_script(scripts: &[String], unchanged: &[String], last_move_wins: bool, options: &PrintOptions) -> String {
    let (header, extensions): (&[&str], &[&str]) = if last_move_wins {
        (
            &[
                "Generated by sieve-gui: runs the active filter scripts in this order",
                "and files each message into at most one folder. Edit those scripts instead.",
            ],
            &["fileinto", "include", "variables"],
        )
    } else {
        (
            &["Generated by sieve-gui: runs the active filter scripts in this order.", "Edit those scripts instead."],
            &["include"],
        )
    };
    let mut require = command("require", vec![list(extensions.iter().map(|e| e.to_string()).collect())], None);
    require.leading_comments = header.iter().map(|line| hash_comment(format!(" {line}"))).collect();

    let mut out = print_command(&require, 0, options);
    if last_move_wins {
        out.push_str(&print_command(&global_command(), 0, options));
    }
    for name in scripts {
        let mut include = command("include", vec![tag("personal"), tag("optional"), string(name)], None);
        if unchanged.contains(name) {
            include.trailing_comment = Some(hash_comment(format!(" {UNCHANGED}")));
        }
        out.push_str(&print_command(&include, 0, options));
    }
    if last_move_wins {
        out.push_str(&print_command(&dispatch_command(), 0, options));
    }
    out
}

/// What `source` does if it is a root script, else `None`. Comments and
/// layout don't matter; the commands must be exactly those of
/// [`root_script`].
pub fn parse_root(source: &str) -> Option<Root> {
    let script = crate::parse(source).ok()?;
    let mut commands: Vec<Command> = script.commands;
    let marked: Vec<bool> = commands.iter().map(is_marked_unchanged).collect();
    commands.iter_mut().for_each(normalize);
    let [require, rest @ ..] = commands.as_slice() else { return None };
    if !require.is("require") {
        return None;
    }
    let (includes, last_move_wins, damaged) = match rest {
        [global, includes @ .., dispatch] if *global == global_command() && *dispatch == dispatch_command() => {
            (includes, true, false)
        }
        [includes @ .., dispatch] if *dispatch == dispatch_command() => (includes, true, true),
        includes => (includes, false, false),
    };
    let scripts: Vec<String> = includes.iter().map(include_name).collect::<Option<_>>()?;
    // The includes start after `require` (and `global`).
    let first = if last_move_wins && !damaged { 2 } else { 1 };
    let unchanged = scripts
        .iter()
        .enumerate()
        .filter(|(i, _)| marked[first + i])
        .map(|(_, name)| name.clone())
        .collect();
    Some(Root { scripts, unchanged, last_move_wins, damaged })
}

fn is_marked_unchanged(cmd: &Command) -> bool {
    cmd.trailing_comment.as_ref().is_some_and(|c| c.text.trim() == UNCHANGED)
}

/// How a script relates to others.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ScriptLinks {
    /// Personal scripts it includes (`include` without `:global`), in
    /// order of appearance, without duplicates.
    pub includes: Vec<String>,
    /// Whether it files messages into folders itself (`fileinto` without
    /// `:copy`), anywhere in the script.
    pub files_messages: bool,
}

/// What `source` includes and whether it moves messages. Unparsable scripts
/// give nothing.
pub fn script_links(source: &str) -> ScriptLinks {
    let mut links = ScriptLinks::default();
    if let Ok(script) = crate::parse(source) {
        collect_links(&script.commands, &mut links);
    }
    links
}

fn collect_links(commands: &[Command], links: &mut ScriptLinks) {
    for cmd in commands {
        let args = &cmd.arguments.args;
        if cmd.is("include")
            && !args.iter().any(|a| a.is_tag("global"))
            && let Some(Argument::String(name)) = args.last()
            && !links.includes.contains(&name.value)
        {
            links.includes.push(name.value.clone());
        }
        if cmd.is("fileinto") && !args.iter().any(|a| a.is_tag("copy")) {
            links.files_messages = true;
        }
        if let Some(block) = &cmd.block {
            collect_links(&block.commands, links);
        }
    }
}

/// `include :personal [:optional] "name"` → the name.
fn include_name(cmd: &Command) -> Option<String> {
    if !cmd.is("include") || cmd.block.is_some() || cmd.arguments.tests.is_some() {
        return None;
    }
    let (name, tags) = cmd.arguments.args.split_last()?;
    let Argument::String(name) = name else { return None };
    let personal = tags.iter().any(|t| t.is_tag("personal"));
    let known = tags.iter().all(|t| t.is_tag("personal") || t.is_tag("optional"));
    (personal && known).then(|| name.value.clone())
}

fn global_command() -> Command {
    command("global", vec![string(FOLDER_VARIABLE)], None)
}

/// `if not string :is "${folder}" "" { fileinto "${folder}"; }`
fn dispatch_command() -> Command {
    let value = format!("${{{FOLDER_VARIABLE}}}");
    let empty = test("string", vec![tag("is"), string(&value), string("")], None);
    let not = test("not", Vec::new(), Some(Tests::Single(Box::new(empty))));
    let mut cmd = command("if", Vec::new(), Some(Tests::Single(Box::new(not))));
    cmd.block = Some(crate::ast::Block {
        commands: vec![command("fileinto", vec![string(&value)], None)],
        trailing_comments: Vec::new(),
        span: Span::default(),
    });
    cmd
}

/// Drops spans, comments and blank lines so that commands compare by content.
fn normalize(cmd: &mut Command) {
    cmd.clear_spans();
    cmd.strip_comments();
}

#[cfg(test)]
mod tests {
    use super::*;

    fn names(list: &[&str]) -> Vec<String> {
        list.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn generates_the_root() {
        let text = root_script(&names(&["Work", "News \"letters\""]), &[], true, &PrintOptions::default());
        assert_eq!(
            text,
            "# Generated by sieve-gui: runs the active filter scripts in this order\n\
             # and files each message into at most one folder. Edit those scripts instead.\n\
             require [\"fileinto\", \"include\", \"variables\"];\n\
             global \"move_to_folder\";\n\
             include :personal :optional \"Work\";\n\
             include :personal :optional \"News \\\"letters\\\"\";\n\
             if not string :is \"${move_to_folder}\" \"\" {\n\
             \tfileinto \"${move_to_folder}\";\n\
             }\n"
        );
        let text = root_script(&names(&["Work"]), &[], false, &PrintOptions::default());
        assert_eq!(
            text,
            "# Generated by sieve-gui: runs the active filter scripts in this order.\n\
             # Edit those scripts instead.\n\
             require [\"include\"];\n\
             include :personal :optional \"Work\";\n"
        );
    }

    #[test]
    fn reads_the_root_back() {
        for list in [vec![], names(&["Work"]), names(&["a", "b \"c\"", "Ä"])] {
            for last_move_wins in [true, false] {
                for options in [PrintOptions::default(), PrintOptions::roundcube()] {
                    // Every second script unchanged.
                    let unchanged: Vec<String> = list.iter().step_by(2).cloned().collect();
                    let root = parse_root(&root_script(&list, &unchanged, last_move_wins, &options));
                    assert_eq!(root, Some(Root { scripts: list.clone(), unchanged, last_move_wins, damaged: false }));
                }
            }
        }
        let edited = "require [\"include\", \"variables\", \"fileinto\"];\r\n# note\r\nglobal \"move_to_folder\";\r\n\
            include :optional :personal \"x\";\r\nif not string :is \"${move_to_folder}\" \"\" { fileinto \"${move_to_folder}\"; }";
        assert_eq!(
            parse_root(edited),
            Some(Root { scripts: names(&["x"]), unchanged: vec![], last_move_wins: true, damaged: false })
        );
    }

    /// Roundcube drops `global` when it saves the root (fixture
    /// `roundcube/24b`); the root is still recognized, as damaged.
    #[test]
    fn reads_a_root_that_lost_global() {
        let text = "require [\"fileinto\", \"include\", \"variables\"];\n\
            include :personal :optional \"x\"; # unchanged\ninclude :personal :optional \"y\";\n\
            if not string :is \"${move_to_folder}\" \"\" { fileinto \"${move_to_folder}\"; }";
        assert_eq!(
            parse_root(text),
            Some(Root { scripts: names(&["x", "y"]), unchanged: names(&["x"]), last_move_wins: true, damaged: true })
        );
    }

    #[test]
    fn marks_unchanged_includes() {
        let text = root_script(&names(&["synomc", "Work"]), &names(&["synomc"]), true, &PrintOptions::default());
        assert!(text.contains("include :personal :optional \"synomc\"; # unchanged\n"), "{text}");
        assert!(text.contains("include :personal :optional \"Work\";\n"), "{text}");
        let root = parse_root(&text).unwrap();
        assert_eq!(root.unchanged, names(&["synomc"]));
    }

    #[test]
    fn links_between_scripts() {
        let links = script_links(
            "require [\"include\", \"fileinto\", \"copy\"];\n\
             include :global :once \"spam\";\n\
             include :personal :optional \"rules\";\n\
             include \"more\";\n\
             if true { include :personal \"rules\"; fileinto :copy \"Archive\"; }",
        );
        assert_eq!(links.includes, names(&["rules", "more"]));
        assert!(!links.files_messages);
        assert!(script_links("require \"fileinto\";\nif true { stop; } elsif false { fileinto \"X\"; }").files_messages);
        assert_eq!(script_links("not sieve {"), ScriptLinks::default());
    }

    #[test]
    fn other_scripts_are_not_roots() {
        let not_roots = [
            "",
            "require \"fileinto\";\nif true { fileinto \"x\"; }",
            // Global without dispatch.
            "require [\"include\", \"variables\"];\nglobal \"move_to_folder\";\ninclude :personal \"x\";",
            // Global include.
            "require \"include\";\ninclude :global \"x\";",
            // Something else in between.
            "require [\"fileinto\", \"include\", \"variables\"];\nglobal \"move_to_folder\";\nkeep;\n\
             if not string :is \"${move_to_folder}\" \"\" { fileinto \"${move_to_folder}\"; }",
        ];
        for src in not_roots {
            assert_eq!(parse_root(src), None, "{src}");
        }
    }
}
