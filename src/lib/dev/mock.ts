/**
 * What saving in MailPlus' web UI does, for checking the watcher in preview
 * mode: rewrites its scripts (here: without filters) and makes `synomc`
 * active again. Call `__mailplusSave()` from the console or a test.
 */
function mailplusSave() {
  const nasServer = servers.nas;
  for (const name of ["filter", "spam_rule"]) nasServer.saved.set(name, (mailplusFixtures as Record<string, Fixture>)[name].source);
  nasServer.active = "synomc";
}

export function installMock() {
  Object.assign(window, { __mailplusSave: mailplusSave });
  mockIPC(async (cmd, args) => {
    const a = (args ?? {}) as Record<string, any>;
    const server = servers[a.id] ?? servers.preview;
    switch (cmd) {
      case "list_accounts":
        return accounts;
      case "connect_account":
        await new Promise((r) => setTimeout(r, 300));
        if (a.id === nas.id && nas.certificate !== NAS_CERTIFICATE.sha256) {
          throw {
            kind: "untrustedCertificate",
            message: "invalid peer certificate: UnknownIssuer",
            diagnostics: [],
            certificate: { service: "manageSieve", certificate: NAS_CERTIFICATE, pinned: nas.certificate },
          };
        }
        return {
          tls: true,
          capabilities: { implementation: "Dovecot Pigeonhole", sasl: ["PLAIN"], sieve, starttls: true, maxRedirects: 4, notify: [], language: null, owner: "me", version: "1.0", unauthenticate: false, other: [] },
          scripts: scriptList(server),
        };
      case "list_folders":
        await new Promise((r) => setTimeout(r, 200));
        // The NAS shows the same certificate for IMAP.
        if (a.id === nas.id && nas.imap.certificate !== NAS_CERTIFICATE.sha256) {
          throw {
            kind: "untrustedCertificate",
            message: "invalid peer certificate: UnknownIssuer",
            diagnostics: [],
            certificate: { service: "imap", certificate: NAS_CERTIFICATE, pinned: nas.imap.certificate },
          };
        }
        return folders;
      case "list_scripts":
        return scriptList(server);
      case "get_script":
        return source(server, a.name) ?? "";
      case "import_rules_single_folder":
      case "script_content":
        // Rough stand-in: without comments and blank lines.
        return (a.source as string).split("\n").map((l) => l.replace(/#.*$/, "").trim()).filter(Boolean).join("\n");
      case "import_rules": {
        const hit = allFixtures.find((s) => s.source === a.source)?.rules ?? generated.get(a.source);
        return hit ? structuredClone(hit) : { preamble: null, requires: [], singleFolder: false, items: [] };
      }
      case "root_script": {
        const includes = (a.scripts as string[]).map(
          (n) => `include :personal :optional ${JSON.stringify(n)};${a.unchanged.includes(n) ? " # unchanged" : ""}`,
        );
        return [ROOT_HEADER, ...(a.lastMoveWins ? ["global \"move_to_folder\";"] : []), ...includes].join("\n");
      }
      case "parse_root": {
        if (!a.source.startsWith(ROOT_HEADER)) return null;
        const lines = [...a.source.matchAll(/^include :personal :optional (".*");( # unchanged)?$/gm)];
        const scripts = lines.map((m) => JSON.parse(m[1]));
        const unchanged = lines.filter((m) => m[2]).map((m) => JSON.parse(m[1]));
        return { scripts, unchanged, lastMoveWins: a.source.includes("global "), damaged: false };
      }
      case "script_links": {
        // Rough stand-in for sieve-core's script_links.
        const includes = [...a.source.matchAll(/include (?![^;]*:global)[^;]*"([^"]+)";/g)].map((m) => m[1]);
        return { includes: [...new Set(includes)], filesMessages: /fileinto (?![^;]*:copy)/.test(a.source) };
      }
      case "save_account": {
        const { password: _, ...input } = a.input;
        const target = accounts.find((x) => x.id === input.id) ?? account;
        Object.assign(target, input, { id: target.id });
        return target;
      }
      case "copy_status": {
        // `?copyDiff`: the preview server lost a script and its active script.
        const differs = a.id === account.id && new URLSearchParams(location.search).has("copyDiff") && !copyResolved;
        if (!differs) return { dir: `~/Library/Application Support/sieve-gui/copies/${a.id}`, differences: [], active: null };
        return {
          dir: `~/Library/Application Support/sieve-gui/copies/${a.id}`,
          differences: [
            { name: "Taxes", server: null, local: "# rule:[Taxes]\nif true { keep; }\n", changed: ["server"], sameRules: false, serverRules: null, localRules: null },
            { name: "Mixed", server: source(server, "Mixed"), local: "# older version\n" + source(server, "Mixed"), changed: ["local"], sameRules: true, serverRules: null, localRules: null },
          ],
          active: { server: "General", local: "sieve-gui" },
        };
      }
      case "resolve_copy":
        copyResolved = true;
        return null;
      case "detect_providers": {
        // Rough stand-in for sieve-core's MailPlus provider.
        const scripts = a.scripts as { name: string; source: string }[];
        const root = scripts.find((s) => s.source.includes('fileinto "${filter_mailbox}"'));
        if (!root) return [];
        const count = (re: RegExp) => scripts.reduce((n, s) => n + (s.source.match(re)?.length ?? 0), 0);
        return [
          {
            provider: "mailplus",
            root: root.name,
            scripts: ["spam_rule", "filter"],
            filters: count(/set "filter_mailbox"/g),
            listEntries: count(/set "spam_rule_(black|white)list_mailbox"/g),
            reactivatesRoot: true,
            fingerprint: String(scripts.filter((s) => s.name === "filter" || s.name === "spam_rule").reduce((n, s) => n + s.source.length, 0)),
          },
        ];
      }
      case "import_provider": {
        const names = a.names as { filter: string; allowList: string; blockList: string };
        const rules = structuredClone(mailplusFilters.import) as { items: { name?: string }[] };
        for (const item of rules.items) {
          item.name = item.name
            ?.replace(/^Allow list/, names.allowList)
            .replace(/^Block list/, names.blockList)
            .replace(/^Filter/, names.filter);
        }
        return rules;
      }
      case "set_filters_alone": {
        const target = accounts.find((x) => x.id === a.id)!;
        Object.assign(target, { filtersAlone: a.value });
        return target;
      }
      case "set_keyword_names": {
        const target = accounts.find((x) => x.id === a.id)!;
        target.keywordNames = a.names;
        return target;
      }
      case "trust_certificate": {
        const target = accounts.find((x) => x.id === a.id)!;
        if (a.service === "manageSieve") target.certificate = a.sha256;
        else if (a.service === "mailPlus") target.mailplus = { port: target.mailplus?.port ?? 5001, certificate: a.sha256 };
        else target.imap.certificate = a.sha256;
        return target;
      }
      case "provider_tags": {
        await new Promise((r) => setTimeout(r, 700));
        if (a.id !== nas.id || a.port !== 5001) {
          throw { kind: "notFound", message: "no MailPlus web API at this address", diagnostics: [], certificate: null };
        }
        const target = accounts.find((x) => x.id === a.id)!;
        if (target.mailplus?.certificate !== DSM_CERTIFICATE.sha256) {
          throw {
            kind: "untrustedCertificate",
            message: "invalid peer certificate: NotValidForName",
            diagnostics: [],
            certificate: { service: "mailPlus", certificate: DSM_CERTIFICATE, pinned: target.mailplus?.certificate ?? null },
          };
        }
        return MAILPLUS_TAGS;
      }
      case "roundcube_risks": {
        // Rough stand-in for sieve-core's check: every raw block counts.
        const items = a.rules.items as { type: string; code?: string }[];
        const raw = items.flatMap((item, i) => (item.type === "raw" ? [i] : []));
        return { rawBlocks: raw, rules: [], bracketComments: raw.some((i) => items[i].code?.includes("/*")) };
      }
      case "export_rules": {
        // Unchanged rules give the original text; real generation needs Rust.
        const hit = allFixtures.find((s) => strip(s.rules) === strip(a.rules));
        if (hit) return hit.source;
        const key = strip(a.rules);
        const known = [...generated].find(([, rules]) => strip(rules) === key);
        if (known) return known[0];
        const text = `# Preview mode: the script is generated by the desktop app.\n# Version ${generated.size + 1}\n`;
        generated.set(text, JSON.parse(key));
        return text;
      }
      case "check_script":
        await new Promise((r) => setTimeout(r, 400));
        return [];
      case "deploy_script":
        server.saved.set(a.name, a.content);
        server.deleted.delete(a.name);
        return [];
      case "activate_script":
        server.active = a.name;
        return null;
      case "delete_script":
        server.saved.delete(a.name);
        server.deleted.add(a.name);
        return null;
      default:
        return null;
    }
  });
}
