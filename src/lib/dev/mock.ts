// Browser preview mode (`pnpm dev` without Tauri): fakes the backend so the
// UI can be developed and reviewed in a normal browser. Never bundled into
// the app (loaded only when `import.meta.env.DEV` and Tauri is absent).
// fixtures.json and fixtures-mailplus.json are produced by sieve-core from
// the Roundcube and MailPlus fixtures.

import { mockIPC } from "@tauri-apps/api/mocks";
import fixtures from "./fixtures.json";
import mailplusFixtures from "./fixtures-mailplus.json";

type Fixture = { source: string; rules: unknown };
/** A fake ManageSieve server: its scripts and which one is active. */
type Server = {
  scripts: Record<string, Fixture>;
  active: string | null;
  /** Scripts saved in preview mode, by name (overrides the fixtures). */
  saved: Map<string, string>;
  deleted: Set<string>;
};
const servers: Record<string, Server> = {
  preview: { scripts: fixtures as Record<string, Fixture>, active: "Allgemein", saved: new Map(), deleted: new Set() },
  // Like Synology MailPlus: its own root script `synomc` is active.
  nas: { scripts: mailplusFixtures as Record<string, Fixture>, active: "synomc", saved: new Map(), deleted: new Set() },
};
const allFixtures = [...Object.values(servers).flatMap((s) => Object.values(s.scripts))];
/** Rules of generated scripts, so that they can be imported again. */
const generated = new Map<string, unknown>();
const ROOT_HEADER = "# Generated by sieve-gui";

const strip = (v: unknown) => JSON.stringify(v, (k, x) => (k === "uid" ? undefined : x));
const source = (server: Server, name: string) =>
  server.deleted.has(name) ? undefined : (server.saved.get(name) ?? server.scripts[name]?.source);
const scriptList = (server: Server) =>
  [...new Set([...Object.keys(server.scripts), ...server.saved.keys()])]
    .filter((name) => !server.deleted.has(name))
    .map((name) => ({ name, active: name === server.active }));

const account = {
  id: "preview",
  label: "Vorschau",
  host: "mail.example.com",
  port: 4190,
  security: "startTls",
  certificate: null as string | null,
  username: "lukas",
  imap: { host: "mail.example.com", port: 993, security: "implicitTls", certificate: null as string | null },
  multipleScripts: true,
  lastMoveWins: true,
  roundcube: false,
};

// A NAS with a self-signed certificate: connecting fails until it is trusted.
const NAS_CERTIFICATE = {
  sha256: "3f9a0c47d2e1b85a6c0d4e7f1a2b3c4d5e6f708192a3b4c5d6e7f8091a2b3c4d",
  subject: "C=US, O=Example NAS CA, OU=server, CN=nas.internal",
  issuer: "C=US, O=Example NAS CA, OU=CA",
  notBefore: 1762128000,
  notAfter: 2077747200,
  names: ["nas.internal", "127.0.0.1", "192.168.1.20"],
};
const nas = {
  ...account,
  id: "nas",
  label: "NAS",
  host: "192.168.1.20",
  imap: { ...account.imap, host: "192.168.1.20" },
};
// `?nasChanged` starts with another certificate trusted, as after a new one.
if (new URLSearchParams(location.search).has("nasChanged")) nas.certificate = "aa".repeat(32);
const accounts = [account, nas];

// Modified UTF-7 names, as IMAP sends them.
const folders = (
  [
    ["INBOX"],
    ["Archiv", "archive"],
    ["Archiv/2025"],
    ["Entw&APw-rfe", "drafts"],
    ["Gesendet", "sent"],
    ["Lists"],
    ["Lists/Rust"],
    ["Papierkorb", "trash"],
    ["Spam", "junk"],
    ["Steuern"],
    ["Steuern/Gesch&AOQ-ftlich"],
    ["Steuern/Privat"],
  ] as [string, string?][]
).map(([name, specialUse]) => ({ name, delimiter: "/", selectable: true, specialUse: specialUse ?? null }));

const sieve = ["fileinto", "include", "reject", "envelope", "vacation", "subaddress", "relational", "regex", "imap4flags", "copy", "body", "variables", "mailbox", "date"];

export function installMock() {
  mockIPC(async (cmd, args) => {
    const a = (args ?? {}) as Record<string, any>;
    const server = servers[a.id] ?? servers.preview;
    switch (cmd) {
      case "list_accounts":
        return accounts;
      case "connect_account":
        await new Promise((r) => setTimeout(r, 300));
        if (a.id === nas.id && nas.certificate !== NAS_CERTIFICATE.sha256) {
          throw {
            kind: "untrustedCertificate",
            message: "invalid peer certificate: UnknownIssuer",
            diagnostics: [],
            certificate: { service: "manageSieve", certificate: NAS_CERTIFICATE, pinned: nas.certificate },
          };
        }
        return {
          tls: true,
          capabilities: { implementation: "Dovecot Pigeonhole", sasl: ["PLAIN"], sieve, starttls: true, maxRedirects: 4, notify: [], language: null, owner: "lukas", version: "1.0", unauthenticate: false, other: [] },
          scripts: scriptList(server),
        };
      case "list_folders":
        await new Promise((r) => setTimeout(r, 200));
        // The NAS shows the same certificate for IMAP.
        if (a.id === nas.id && nas.imap.certificate !== NAS_CERTIFICATE.sha256) {
          throw {
            kind: "untrustedCertificate",
            message: "invalid peer certificate: UnknownIssuer",
            diagnostics: [],
            certificate: { service: "imap", certificate: NAS_CERTIFICATE, pinned: nas.imap.certificate },
          };
        }
        return folders;
      case "list_scripts":
        return scriptList(server);
      case "get_script":
        return source(server, a.name) ?? "";
      case "import_rules": {
        const hit = allFixtures.find((s) => s.source === a.source)?.rules ?? generated.get(a.source);
        return hit ? structuredClone(hit) : { preamble: null, requires: [], singleFolder: false, items: [] };
      }
      case "root_script": {
        const includes = (a.scripts as string[]).map(
          (n) => `include :personal :optional ${JSON.stringify(n)};${a.unchanged.includes(n) ? " # unchanged" : ""}`,
        );
        return [ROOT_HEADER, ...(a.lastMoveWins ? ["global \"move_to_folder\";"] : []), ...includes].join("\n");
      }
      case "parse_root": {
        if (!a.source.startsWith(ROOT_HEADER)) return null;
        const lines = [...a.source.matchAll(/^include :personal :optional (".*");( # unchanged)?$/gm)];
        const scripts = lines.map((m) => JSON.parse(m[1]));
        const unchanged = lines.filter((m) => m[2]).map((m) => JSON.parse(m[1]));
        return { scripts, unchanged, lastMoveWins: a.source.includes("global ") };
      }
      case "script_links": {
        // Rough stand-in for sieve-core's script_links.
        const includes = [...a.source.matchAll(/include (?![^;]*:global)[^;]*"([^"]+)";/g)].map((m) => m[1]);
        return { includes: [...new Set(includes)], filesMessages: /fileinto (?![^;]*:copy)/.test(a.source) };
      }
      case "save_account": {
        const { password: _, ...input } = a.input;
        const target = accounts.find((x) => x.id === input.id) ?? account;
        Object.assign(target, input, { id: target.id });
        return target;
      }
      case "trust_certificate": {
        const target = accounts.find((x) => x.id === a.id)!;
        if (a.service === "manageSieve") target.certificate = a.sha256;
        else target.imap.certificate = a.sha256;
        return target;
      }
      case "roundcube_risks": {
        // Rough stand-in for sieve-core's check: every raw block counts.
        const items = a.rules.items as { type: string; code?: string }[];
        const raw = items.flatMap((item, i) => (item.type === "raw" ? [i] : []));
        return { rawBlocks: raw, rules: [], bracketComments: raw.some((i) => items[i].code?.includes("/*")) };
      }
      case "export_rules": {
        // Unchanged rules give the original text; real generation needs Rust.
        const hit = allFixtures.find((s) => strip(s.rules) === strip(a.rules));
        if (hit) return hit.source;
        const key = strip(a.rules);
        const known = [...generated].find(([, rules]) => strip(rules) === key);
        if (known) return known[0];
        const text = `# Preview mode: the script is generated by the desktop app.\n# Version ${generated.size + 1}\n`;
        generated.set(text, JSON.parse(key));
        return text;
      }
      case "check_script":
        await new Promise((r) => setTimeout(r, 400));
        return [];
      case "deploy_script":
        server.saved.set(a.name, a.content);
        server.deleted.delete(a.name);
        return [];
      case "activate_script":
        server.active = a.name;
        return null;
      case "delete_script":
        server.saved.delete(a.name);
        server.deleted.add(a.name);
        return null;
      default:
        return null;
    }
  });
}
