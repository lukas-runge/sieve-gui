// Browser preview mode (`pnpm dev` without Tauri): fakes the backend so the
// UI can be developed and reviewed in a normal browser. Never bundled into
// the app (loaded only when `import.meta.env.DEV` and Tauri is absent).
// fixtures.json is produced by sieve-core from the Roundcube fixtures.

import { mockIPC } from "@tauri-apps/api/mocks";
import fixtures from "./fixtures.json";

type Fixture = { source: string; rules: unknown };
const scripts = fixtures as Record<string, Fixture>;
let active = "Allgemein";

const account = {
  id: "preview",
  label: "Vorschau",
  host: "mail.example.com",
  port: 4190,
  security: "startTls",
  username: "lukas",
};

const sieve = ["fileinto", "reject", "envelope", "vacation", "subaddress", "relational", "regex", "imap4flags", "copy", "body", "variables", "mailbox", "date"];

export function installMock() {
  mockIPC(async (cmd, args) => {
    const a = (args ?? {}) as Record<string, any>;
    switch (cmd) {
      case "list_accounts":
        return [account];
      case "connect_account":
        await new Promise((r) => setTimeout(r, 300));
        return {
          tls: true,
          capabilities: { implementation: "Dovecot Pigeonhole", sasl: ["PLAIN"], sieve, starttls: true, maxRedirects: 4, notify: [], language: null, owner: "lukas", version: "1.0", unauthenticate: false, other: [] },
          scripts: Object.keys(scripts).map((name) => ({ name, active: name === active })),
        };
      case "list_scripts":
        return Object.keys(scripts).map((name) => ({ name, active: name === active }));
      case "get_script":
        return scripts[a.name]?.source ?? "";
      case "import_rules": {
        const hit = Object.values(scripts).find((s) => s.source === a.source);
        return hit ? structuredClone(hit.rules) : { preamble: null, requires: [], items: [] };
      }
      case "export_rules": {
        // Unchanged rules give the original text; real generation needs Rust.
        const strip = (v: unknown) => JSON.stringify(v, (k, x) => (k === "uid" ? undefined : x));
        const hit = Object.values(scripts).find((s) => strip(s.rules) === strip(a.rules));
        return hit?.source ?? "# Preview mode: the script is generated by the desktop app.\n";
      }
      case "check_script":
        await new Promise((r) => setTimeout(r, 400));
        return [];
      case "deploy_script":
        return [];
      case "activate_script":
        active = a.name;
        return null;
      default:
        return null;
    }
  });
}
