const dictionaries = { en, de } as const;
export type Locale = keyof typeof dictionaries;

function detect(): Locale {
  const lang = typeof navigator === "undefined" ? "en" : navigator.language;
  return lang.toLowerCase().startsWith("de") ? "de" : "en";
}

export const i18n = $state({ locale: detect() as Locale });

/** Translates a key, replacing `{name}` placeholders. */
export function t(key: MessageKey, params: Record<string, string | number> = {}): string {
  const text: string = dictionaries[i18n.locale][key] ?? en[key];
  return text.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? `{${name}}`));
}
